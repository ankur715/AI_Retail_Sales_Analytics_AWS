"""Dummy retailer sell-through data, in each retailer's own (messy) layout.

Every retailer reports week-ending-Saturday sales and on-hand inventory, but
each one has its own file shape -- that's why a parser sits in front of the
load:

    R201 Northgate  serial level  CSV   MM/DD/YYYY dates, "$1,234.50" sales, serial numbers with leading zeros
    R202 Summit     SKU level     XLSX  title row above the header, one row per store
    R203 Harbor     style level   CSV   lower-case padded headers, one row per store, a TOTAL row at the bottom
    API  (C102 at R202)           JSON  camelCase fields, cursor-paged (see mock_api/)

Restatements: a retailer re-sends the last 5 weeks in every weekly file, and
the numbers for those weeks drift (returns, late POS uploads) until a week
is 4 weeks old. `as_of` is the week the file was produced; values are a
pure function of (product, store, week, as_of), so any file can be
regenerated byte-for-byte.

Usage:
    python -m data_gen.generate --week-end 2026-09-26 --weeks 12            # history files
    python -m data_gen.generate --week-end 2026-10-03 --weeks 5 --upload    # next weekly drop -> S3 landing
    python -m data_gen.generate --week-end 2026-10-10 --parts 2 --only C101_R201 --upload   # a drop split in 2 files
"""
import argparse
import csv
import io
from datetime import date, datetime, timedelta
from pathlib import Path

from openpyxl import Workbook

from data_gen.catalog import (
    CLIENTS, RETAILERS, UNMAPPED_SERIAL, UNMAPPED_SKU, UNMAPPED_STYLE,
    load_pipelines, skus, stable_rng,
)
from etl.weeks import is_week_end, week_range

LOCAL_OUT = Path(__file__).resolve().parent.parent / "data" / "landing"
STORES = {"sku": [101, 102], "style": [301, 302, 303]}   # serial feeds are already chain-level
RESTATE_WEEKS = 4                                         # numbers settle once a week is 4 weeks old


def _units(client, retailer, key, store, week: date, as_of: date) -> tuple[int, int]:
    """(units sold, units on hand) for one product/store/week as reported in
    the file produced on `as_of`."""
    base = stable_rng(client, retailer, key, store, week)
    units, on_hand = base.randint(0, 40), base.randint(10, 200)
    age = min((as_of - week).days // 7, RESTATE_WEEKS)
    for k in range(1, age + 1):   # each later file adjusts the week a little
        units += stable_rng(client, retailer, key, store, week, k).randint(-2, 3)
    return max(units, 0), on_hand


def normalized_rows(client: str, retailer: str, level: str, weeks: list[date], as_of: date) -> list[dict]:
    """Rows at the retailer's grain, in standard column names (before the
    retailer-specific formatting is applied)."""
    catalog = skus(client)
    rows = []
    for week in weeks:
        if level == "serial":
            keys = [(s.serial, s.unit_price) for s in catalog] + [(UNMAPPED_SERIAL[client], 24.99)]
            for serial, unit_price in keys:
                units, on_hand = _units(client, retailer, serial, 0, week, as_of)
                rows.append({"week_date": week, "client_id": client, "retailer_id": retailer,
                             "product_id": serial, "sales": round(units * unit_price, 2), "inventory": on_hand})
        elif level == "sku":
            keys = [(s.style, s.color, s.size, s.unit_price) for s in catalog]
            keys.append((*UNMAPPED_SKU, catalog[8].unit_price))   # catalog[8] is S03: same style, a color that isn't set up
            for store in STORES["sku"]:
                for style, color, size, unit_price in keys:
                    units, on_hand = _units(client, retailer, (style, color, size), store, week, as_of)
                    rows.append({"week_date": week, "client_id": client, "retailer_id": retailer,
                                 "store": store, "style": style, "color": color, "size": size,
                                 "sales": round(units * unit_price, 2), "inventory": on_hand})
        elif level == "style":
            styles = sorted({s.style for s in catalog}) + [UNMAPPED_STYLE]
            for store in STORES["style"]:
                for style in styles:
                    unit_price = next((s.unit_price for s in catalog if s.style == style), 15.0)
                    units, on_hand = _units(client, retailer, style, store, week, as_of)
                    units *= 4   # a style is ~4 SKUs
                    rows.append({"week_date": week, "client_id": client, "retailer_id": retailer,
                                 "store": store, "style": style,
                                 "sales": round(units * unit_price, 2), "inventory": on_hand * 4})
        else:
            raise ValueError(f"Unknown product level {level!r}")
    return rows


