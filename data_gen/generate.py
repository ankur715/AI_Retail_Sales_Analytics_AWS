# Retailer-specific layouts
# ---------------------------------------------------------------------------

def render_r201_csv(rows: list[dict]) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf, quoting=csv.QUOTE_MINIMAL)
    w.writerow(["Week_Date", "Client", "Retailer", "Product_ID", "Sales", "Inventory"])
    for r in rows:
        w.writerow([r["week_date"].strftime("%m/%d/%Y"), r["client_id"], r["retailer_id"],
                    r["product_id"], f"${r['sales']:,.2f}", r["inventory"]])
    return buf.getvalue().encode()


def render_r202_xlsx(rows: list[dict]) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Sell Thru"
    ws.append(["Summit Outfitters - weekly vendor sell-through"])   # title row above the header
    ws.append(["Week Date", "Retailer", "Client", "Store", "Style", "Color", "Size", "Sales $", "Inventory Units"])
    for r in rows:
        ws.append([datetime.combine(r["week_date"], datetime.min.time()), r["retailer_id"], r["client_id"],
                   r["store"], r["style"], r["color"], r["size"], r["sales"], r["inventory"]])
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def render_r203_csv(rows: list[dict]) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow([" week_date ", "retailer", "client", "store", "style", "sales", "inventory"])
    for r in rows:
        w.writerow([r["week_date"].isoformat(), r["retailer_id"], r["client_id"], r["store"],
                    r["style"], f"{r['sales']:.2f}", r["inventory"]])
    # Harbor Mart's export appends a grand-total line -- the parser must drop it.
    w.writerow(["", "", "", "", "TOTAL", f"{sum(r['sales'] for r in rows):.2f}", sum(r["inventory"] for r in rows)])
    return buf.getvalue().encode()


def api_records(rows: list[dict]) -> list[dict]:
    """The mock API's JSON shape (camelCase, ISO dates)."""
    return [{"weekEnding": r["week_date"].isoformat(), "clientId": r["client_id"], "retailerId": r["retailer_id"],
             "storeNumber": r["store"], "style": r["style"], "color": r["color"], "size": r["size"],
             "salesAmount": r["sales"], "onHandUnits": r["inventory"]} for r in rows]


RENDERERS = {"csv": render_r201_csv, "xlsx": render_r202_xlsx}


def render(pipeline: dict, rows: list[dict]) -> bytes:
    if pipeline["retailer_id"] == "R203":
        return render_r203_csv(rows)
    return RENDERERS[pipeline["file_format"]](rows)


def file_name(client: str, retailer: str, week_end: date, ext: str, part: int | None = None) -> str:
    return f"{retailer}_{client}_{week_end:%Y%m%d}{f'_part{part}' if part else ''}.{ext}"


def generate(week_end: date, weeks: int, upload: bool = False, parts: int = 1,
             only: list[str] | None = None) -> list[str]:
    if not is_week_end(week_end):
        raise SystemExit(f"--week-end must be a Saturday, got {week_end} ({week_end:%A})")
    window = week_range(week_end - timedelta(weeks=weeks - 1), week_end)
    written = []
    for p in load_pipelines():
        if p["source_type"] != "s3" or (only and p["pipeline_id"] not in only):
            continue   # the API pipeline pulls from mock_api at run time
        rows = normalized_rows(p["client_id"], p["retailer_id"], p["product_level"], window, as_of=week_end)
        for part in range(1, parts + 1):
            chunk = rows[part - 1::parts]   # a split drop: every part has its own share of the rows
            name = file_name(p["client_id"], p["retailer_id"], week_end, p["file_format"], part if parts > 1 else None)
            body = render(p, chunk)
            if upload:
                from etl import config, s3_io   # only needed for --upload
                key = config.s3_key(p["source_location"], name)
                s3_io.put_bytes(key, body)
                written.append(f"s3://{config.S3_BUCKET}/{key}")
            else:
                path = LOCAL_OUT / p["client_id"] / p["retailer_id"] / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(body)
                written.append(str(path))
    return written


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--week-end", required=True, type=date.fromisoformat, help="last week in the file (a Saturday)")
    ap.add_argument("--weeks", type=int, default=5, help="weeks per file: 12 for history, 5 for a weekly drop")
    ap.add_argument("--upload", action="store_true", help="write to s3://$S3_BUCKET/$RETAIL_ENV/landing/ instead of data/landing/")
    ap.add_argument("--parts", type=int, default=1, help="split each drop into N _partN files")
    ap.add_argument("--only", nargs="*", help="pipeline ids to generate (default: every S3 pipeline)")
    args = ap.parse_args()
    for path in generate(args.week_end, args.weeks, args.upload, args.parts, args.only):
        print(path)


if __name__ == "__main__":
    main()
